EFFECT_NO_EFFECT = "NO_EFFECT"
EFFECT_LOCAL = "LOCAL_CHANGE"
EFFECT_GLOBAL = "GLOBAL_CHANGE"
EFFECT_LEVEL = "LEVEL_ADVANCED"

EVIDENCE_VERIFIED = "VERIFIED"        # M-A analog: frame prediction validated
EVIDENCE_CORROBORATED = "CORROBORATED"  # M-B analog: consistent, unvalidated

STATUS_ACTIVE = "ACTIVE"
STATUS_STALE = "STALE"                # contradicted/superseded — surfaced, kept
STATUS_QUARANTINED = "QUARANTINED"    # exhausted — terminal for the episode

BLACKLIST_CAP = 64
SEQ_STORE_CAP = 60
GLOBAL_CHANGE_FRACTION = 0.25


class EpisodeLedger:
    """Append-only event log (UL R9). Everything else is a projection."""

    def __init__(self):
        self.events = []

    def append(self, kind, **payload):
        eid = len(self.events)
        self.events.append(dict(id=eid, kind=kind, **payload))
        return eid

    def __len__(self):
        return len(self.events)


class RuleRecord:
    """A learned rule with evidence class and status (UL R5/R6/R12 — no
    scalar scores, contradictions surface, quarantine is terminal)."""

    def __init__(self, rule_id, kind):
        self.rule_id = rule_id
        self.kind = kind
        self.evidence_class = None
        self.status = STATUS_ACTIVE
        self.success = 0
        self.fail = 0
        self.rotations = 0
        self.evidence = []  # ledger event ids

    def cite(self, eid):
        self.evidence.append(eid)


class GameKnowledge:
    """Cross-level / cross-episode knowledge for one game (projection)."""

    def __init__(self, game_id):
        self.game_id = game_id
        self.rules = {}     # selector name -> RuleRecord
        self.move = None    # {"dirs": {aid: (dr,dc)}, "player_color", "record"}
        self.sequences = {}  # level -> {"actions": [...], "evidence_class",
        #                       "aborts": int, "stale": bool}

    def rule(self, name):
        if name not in self.rules:
            self.rules[name] = RuleRecord(name, "click")
        return self.rules[name]

    def best_selector(self, order):
        """Level-1-first (F3): prefer rules that have succeeded, VERIFIED
        before CORROBORATED; never quarantined; stale goes last."""
        def key(sel):
            rec = self.rules.get(sel)
            if rec is None:
                return (2, 0, 0)          # untried: middle
            if rec.status == STATUS_QUARANTINED:
                return (9, 0, 0)
            if rec.status == STATUS_STALE:
                return (1, 0, 0)
            rank = {EVIDENCE_VERIFIED: 0, EVIDENCE_CORROBORATED: 1, None: 2}
            return (0, rank.get(rec.evidence_class, 2), -rec.success)
        return sorted(order, key=key)


def classify_effect(prev, cur, levels_before, levels_after):
    """F1: classify the observed effect of the last action."""
    if levels_after > levels_before:
        return EFFECT_LEVEL, 0
    d = frame_diff(prev, cur)
    n = int(d.sum())
    if n == 0:
        return EFFECT_NO_EFFECT, 0
    if n > GLOBAL_CHANGE_FRACTION * prev.size or n > 1024:
        return EFFECT_GLOBAL, n
    return EFFECT_LOCAL, n


